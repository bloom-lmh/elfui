#!/usr/bin/env node
import { performance } from "node:perf_hooks";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

import { elfuiMacroPlugin } from "../packages/compiler/dist/vite.js";

const root = resolve(".");
const args = process.argv.slice(2);
const hasArg = (name) => args.includes(`--${name}`);
const readArg = (name) => {
  const prefix = `--${name}=`;
  return args.find((arg) => arg.startsWith(prefix))?.slice(prefix.length);
};

const sourceFor = (index) => `
import { defineHtml, defineProps } from "@elfui/core";

const props = defineProps({
  label: { type: String, default: "row" },
  count: { type: Number, default: ${index} }
});

export default defineHtml(\`
  <button data-index="${index}">\${props.label}: \${props.count}</button>
\`);
`;

let diagnostics = 0;
const plugin = elfuiMacroPlugin({
  projectRoot: root,
  strictDiagnostics: true,
  templateTypeCheck: false,
  onDiagnostics(items) {
    diagnostics += items.length;
  }
});

const transformFiles = (count, offset) => {
  const startedAt = performance.now();
  let outputBytes = 0;
  for (let index = 0; index < count; index++) {
    const fileIndex = offset + index;
    const result = plugin.transform?.(
      sourceFor(fileIndex),
      resolve(root, "benchmark", `MacroBench${fileIndex}.elf.ts`)
    );
    if (!result || !result.code.includes("__elfDefineComponent")) {
      throw new Error(`macro transform did not produce a component for file ${fileIndex}`);
    }
    outputBytes += result.code.length;
  }
  const duration = performance.now() - startedAt;
  return {
    count,
    duration,
    filesPerSecond: (count / duration) * 1000,
    outputBytes
  };
};

transformFiles(20, 0);
const small = transformFiles(100, 100);
const large = transformFiles(1000, 1000);
const results = [small, large];

const formatMs = (value) => `${value.toFixed(2)} ms`;
const formatRate = (value) => `${value.toFixed(1)} files/s`;

if (hasArg("json")) {
  console.log(JSON.stringify({ diagnostics, results }, null, 2));
} else {
  console.log("\nElfUI macro transform benchmark\n");
  for (const result of results) {
    console.log(
      `${result.count} files: ${formatMs(result.duration)} (${formatRate(result.filesPerSecond)})`
    );
  }
}

const reportPath = readArg("report");
if (reportPath) {
  const outputPath = resolve(root, reportPath);
  const lines = [
    "# ElfUI Macro Transform Benchmark",
    "",
    `> Generated by \`pnpm benchmark:macro\` on ${new Date().toISOString()}.`,
    "",
    "| Files | Duration | Throughput | Generated code |",
    "| ---: | ---: | ---: | ---: |",
    ...results.map(
      (result) =>
        `| ${result.count} | ${formatMs(result.duration)} | ${formatRate(result.filesPerSecond)} | ${(result.outputBytes / 1024).toFixed(2)} KB |`
    ),
    ""
  ];
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, lines.join("\n"), "utf8");
}

if (hasArg("check")) {
  const maximumLinearDuration = small.duration * 15 + 250;
  if (diagnostics !== 0) {
    console.error(`macro transform emitted ${diagnostics} diagnostics`);
    process.exit(1);
  }
  if (large.duration > maximumLinearDuration) {
    console.error(
      `macro transform scaling regression: 1,000 files ${formatMs(large.duration)} / limit ${formatMs(maximumLinearDuration)}`
    );
    process.exit(1);
  }
  console.log("macro transform regression checks passed");
}
